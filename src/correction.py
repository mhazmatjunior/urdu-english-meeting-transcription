"""
Text Correction + Translation Module
=====================================
Two separate API calls for better quality:

  Call 1 — Urdu Correction:
    Input:  raw ASR text (garbled, code-mixed)
    Output: clean corrected Urdu text

  Call 2 — English Translation:
    Input:  corrected Urdu (clean!)
    Output: fluent English translation

Why 2 calls > 1 call:
  - Translator gets clean input, not garbled ASR
  - Each call focused on one task = better quality
  - Easier to debug (can see correction before translation)
"""

import time
import json
import logging
import random

from groq import Groq
from .config import TRANSLATION_CONFIG as GROQ_CONFIG

logger = logging.getLogger(__name__)

# ── Prompts ───────────────────────────────────────────────────

CORRECTION_SYSTEM_PROMPT = """# Urdu ASR Transcript Normalization

You are an Urdu ASR transcript normalization system.

The input is a transcript generated by Whisper Large from spoken Urdu audio.

## Rules

1. Correct only obvious ASR recognition errors using the surrounding context.

2. Correct spelling mistakes caused by ASR recognition.

3. Preserve the speaker's original wording, sentence order, and speaking style.

4. Do NOT rewrite, paraphrase, summarize, improve grammar, or complete incomplete sentences.

5. If the speaker used an English word while speaking Urdu, write it in its standard English spelling (Latin script).

6. Do NOT translate Urdu words into English.

Example:

میں نے File Save کی۔

must NOT become

I saved the file.

7. Do NOT replace English words with their Urdu equivalents else, write that english words written in urdu in English writing.

Example:
Input

اس ڈاکیومنٹ کو اپ لوڈ کر دو۔

Output

اس Document کو Upload کر دو۔

Input

پہلے فائل کو سیو کر دو۔

Output

پہلے File کو Save کر دو۔

8. Use context only to determine whether a recognized word is incorrect.

9. Do not modify words that are already correct.

10. If the input is already correct dont need to mention that, jusst simply rewrite it as it is.
## CRITICAL OUTPUT RULES
- Return ONLY the corrected Urdu text
- NO explanations, NO notes in brackets like (corrected) or (no change needed)
- NO arrows → showing changes  
- NO English commentary
- If no corrections needed, return the original text exactly as-is
- Just the text, nothing else"""

TRANSLATION_SYSTEM_PROMPT = """#  Context-Aware Urdu-to-English Translation

You are an expert translator.

The input is a corrected Urdu transcript.

Your task is to translate it into natural English while preserving the speaker's intended meaning.

## Rules

1. Translate the meaning, not individual words.

2. Produce fluent, natural English.

3. You may reorder words or change sentence structure whenever necessary to produce natural English.

4. Do not add information that was not spoken.

5. Do not omit information that was spoken.

6. If the Urdu sentence is grammatically incorrect but its meaning is clear, translate the intended meaning into natural English.

7. If the Urdu sentence is ambiguous, preserve the ambiguity instead of guessing.

8. Preserve technical terms already written in English (Python, API, ChatGPT, GitHub, Login, etc.).

9. Transliterate proper names written in Urdu into their standard English spellings.

10. Return only the English translation."""

class AdvancedCorrectionPipeline:
    """Two-step Urdu correction + English translation pipeline."""

    def __init__(self, config: dict = None):
        self.config   = config or GROQ_CONFIG
        self.client   = Groq(api_key=self.config["api_key"])
        self.model    = self.config["model"]
        self._previous_corrected = ""   # rolling context for correction
        self._previous_translated = ""  # rolling context for translation
        logger.info("AdvancedCorrectionPipeline initialized (2-step)")

    # ──────────────────────────────────────────────────────────
    # CALL 1 — Urdu Correction
    # ──────────────────────────────────────────────────────────

    def _correct_urdu(self, raw_text: str, speaker: str = "") -> str:
        """
        Fix ASR errors in raw Urdu text.
        Returns clean corrected Urdu string.
        """
        context_note = ""
        if self._previous_corrected:
            context_note = (
                f"\nPrevious segment (for context): "
                f"{self._previous_corrected[-200:]}"
            )

        user_message = f"{context_note}\nCorrect this ASR text:\n{raw_text}"

        for attempt in range(3):
            try:
                response = self.client.chat.completions.create(
                    model=self.model,
                    messages=[
                        {"role": "system", "content": CORRECTION_SYSTEM_PROMPT},
                        {"role": "user",   "content": user_message},
                    ],
                    temperature=0.1,    # low = consistent, factual corrections
                    max_tokens=500,
                )

                corrected = response.choices[0].message.content.strip()

                # Sanity check — if response is too long or empty, fallback
                if not corrected:
                    return raw_text

                return corrected

            except Exception as e:
                err = str(e)
                if "rate_limit" in err.lower() or "429" in err:
                    wait = 60 + random.randint(10, 30)
                    logger.warning(f"Rate limit hit (correction) — waiting {wait}s")
                    time.sleep(wait)
                else:
                    logger.error(f"Correction error (attempt {attempt+1}): {e}")
                    time.sleep(2.1)

        # All attempts failed — return raw
        logger.error("Correction failed after 3 attempts — returning raw text")
        return raw_text

    # ──────────────────────────────────────────────────────────
    # CALL 2 — English Translation
    # ──────────────────────────────────────────────────────────

    def _translate_to_english(self, corrected_text: str, speaker: str = "") -> str:
        """
        Translate corrected Urdu text to fluent English.
        Returns English translation string.
        """
        context_note = ""
        if self._previous_translated:
            context_note = (
                f"\nPrevious English translation (for context): "
                f"{self._previous_translated[-200:]}"
            )

        user_message = f"{context_note}\nTranslate to English:\n{corrected_text}"

        for attempt in range(3):
            try:
                response = self.client.chat.completions.create(
                    model=self.model,
                    messages=[
                        {"role": "system", "content": TRANSLATION_SYSTEM_PROMPT},
                        {"role": "user",   "content": user_message},
                    ],
                    temperature=0.2,    # slightly higher for natural translation
                    max_tokens=500,
                )

                translation = response.choices[0].message.content.strip()

                if not translation:
                    return ""

                return translation

            except Exception as e:
                err = str(e)
                if "rate_limit" in err.lower() or "429" in err:
                    wait = 60 + random.randint(10, 30)
                    logger.warning(f"Rate limit hit (translation) — waiting {wait}s")
                    time.sleep(wait)
                else:
                    logger.error(f"Translation error (attempt {attempt+1}): {e}")
                    time.sleep(2.1)

        logger.error("Translation failed after 3 attempts — returning empty")
        return ""

    # ──────────────────────────────────────────────────────────
    # MAIN — Two-step processing
    # ──────────────────────────────────────────────────────────

    def correct_segment_advanced(
        self, raw_text: str, speaker: str = ""
    ) -> dict:
        """
        Two-step processing per segment:
          Step 1: Correct ASR errors in Urdu
          Step 2: Translate corrected Urdu → English

        Returns:
            {
                "corrected_text": str,   # clean Urdu
                "translation_en": str,   # fluent English
                "changed": bool,         # whether text was modified
            }
        """
        if not raw_text.strip():
            return {
                "corrected_text": "",
                "translation_en": "",
                "changed": False,
            }

        # ── Step 1: Correct Urdu ─────────────────────────────
        corrected = self._correct_urdu(raw_text, speaker)
        time.sleep(2.1)   # rate limit gap between calls

        # ── Step 2: Translate to English ─────────────────────
        translation = self._translate_to_english(corrected, speaker)
        time.sleep(2.1)   # rate limit gap between segments

        # ── Update rolling context ────────────────────────────
        self._previous_corrected  = corrected
        self._previous_translated = translation

        return {
            "corrected_text": corrected,
            "translation_en": translation,
            "changed": corrected.strip() != raw_text.strip(),
        }

# ── Quick standalone functions ────────────────────────────────

def correct_and_translate(
    segments: list, config: dict = None
) -> list:
    """Process all segments through correction + translation."""
    pipeline = AdvancedCorrectionPipeline(config)
    for seg in segments:
        result = pipeline.correct_segment_advanced(
            seg.get("text", ""),
            speaker=seg.get("speaker", ""),
        )
        seg["corrected_text"] = result["corrected_text"]
        seg["translation_en"] = result["translation_en"]
    return segments

